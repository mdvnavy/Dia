def test_assistant_segmented_control_reuses_icon_style_component_below_it():
    assert INDEX.index('id="iconStyleTitle"') < INDEX.index('id="assistantTitle">Assistant</h3>')
    group = re.search(r'<div class="icon-style-control assistant-control" role="radiogroup"[^>]*>', INDEX).group(0)
    assert 'aria-labelledby="assistantTitle"' in group and 'aria-describedby="assistantHelp"' in group
    for mode, label, checked, tab in (("guided", "Guided", "true", "0"), ("expert", "Expert", "false", "-1"), ("off", "Off", "false", "-1")):
        assert (f'role="radio" class="icon-style-option assistant-option" data-assistant-mode="{mode}" '
                f'aria-checked="{checked}" tabindex="{tab}">{label}</button>') in INDEX
    # Applied before first paint, saved per device, invalid values fall back to guided.
    assert 'localStorage.getItem("dia-assistant")' in INDEX and "/^(guided|expert|off)$/" in INDEX
    assert "localStorage.setItem(ASSISTANT_KEY" in APP_JS
    # The icon-style radios must not pick up the assistant options.
    assert 'querySelectorAll(".icon-style-option[data-icon-style]")' in APP_JS


