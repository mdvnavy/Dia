def test_multi_file_merge_is_decided_and_in_one_function():
    assert "provisional" not in APP_JS.lower()
    assert "MULTI_FILE_MODE" not in APP_JS
    assert len(re.findall(r"function combineExtracted\(", APP_JS)) == 1
