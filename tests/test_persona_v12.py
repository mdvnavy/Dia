def test_segmented_control_arrows_apply_and_persist(context, base_url):
    page = open_page(context, base_url)
    assert page.evaluate("document.documentElement.dataset.assistant") == "guided"
    assert page.evaluate("localStorage.getItem('dia-assistant')") is None  # nothing written on first run
    page.evaluate("openHelp()")
    page.focus('[data-assistant-mode="guided"]')
    page.keyboard.press("ArrowRight")
    assert page.evaluate("document.documentElement.dataset.assistant") == "expert"
    assert page.get_attribute('[data-assistant-mode="expert"]', "aria-checked") == "true"
    assert page.evaluate("document.activeElement.dataset.assistantMode") == "expert"
    page.keyboard.press("ArrowRight")
    assert page.evaluate("localStorage.getItem('dia-assistant')") == "off"
    page.keyboard.press("ArrowRight")  # wraps
    assert page.evaluate("document.documentElement.dataset.assistant") == "guided"
    # Icon style is untouched by the assistant control.
    assert page.evaluate("document.documentElement.dataset.iconStyle") == "line"
    page.click('[data-assistant-mode="expert"]')
    page.reload()
    page.wait_for_function("document.querySelector('#agentStatus').textContent !== 'checking...'")
    assert page.evaluate("document.documentElement.dataset.assistant") == "expert"
    page.evaluate("openHelp()")
    assert page.get_attribute('[data-assistant-mode="expert"]', "aria-checked") == "true"
    assert page.get_attribute('[data-assistant-mode="expert"]', "tabindex") == "0"
    assert page.errors == []


