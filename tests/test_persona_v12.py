def open_page(context, base_url, *, configured=True, agent_calls=None):
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.route("**/api/agent/status", lambda r: r.fulfill(json={"configured": configured}))

    def agent(route):
        if agent_calls is not None:
            agent_calls.append(json.loads(route.request.post_data))
        route.fulfill(json={"reply": "1. What budget range have you set aside for this phase?\n2. Who signs off on this engagement?"})

    page.route("**/api/agent", agent)
    page.goto(base_url + "/")
    page.wait_for_function("document.querySelector('#agentStatus').textContent !== 'checking...'")
    page.errors = errors
    return page


def run_intake(page, text):
    page.evaluate("() => { latestPayload = null; if (!intakeToggle.hidden) setIntakeCollapsed(false); }")
    page.evaluate("t => { const q = document.querySelector('#questionnaire'); q.value = t; q.dispatchEvent(new Event('input')); }", text)
    page.click("#runAgent")
    page.wait_for_function("latestPayload !== null && document.body.dataset.stage === 'results'")


def test_button_shows_only_with_issues_and_drafts_into_ask_dia(context, base_url):
    calls = []
    page = open_page(context, base_url, agent_calls=calls)
    run_intake(page, COMPLETE)
    assert page.is_hidden("#draftFollowups")  # no issues, no button (persona rule 3)
    run_intake(page, MISSING)
    assert page.is_visible("#draftFollowups") and page.inner_text("#followupLabel") == AI_LABEL
    assert calls == []  # never automatic
    page.click("#draftFollowups")
    page.wait_for_function("document.querySelector('#agentOutput').textContent.startsWith('1.')")
    assert len(calls) == 1 and "validation issue" in calls[0]["message"]
    assert page.is_visible("#agentAiLabel") and page.is_visible("#copyQuestions")
    assert page.inner_text("#agentAiLabel") == AI_LABEL
    # The draft never reaches the exported documents.
    assert "budget range have you set aside" not in page.evaluate("buildMarkdownExport()")
    assert page.errors == []


